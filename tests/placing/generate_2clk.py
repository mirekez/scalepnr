#!/usr/bin/env python3
"""Calibrate one two-clock size tier, after the preceding tier has passed."""
import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
import json
from pathlib import Path
import tempfile

from generate import FAMILIES, render as render_single
from run import synthesize, constraint_tcl

ROOT = Path(__file__).resolve().parent
SIZES = ['1k', '5k', '10k', '30k', '50k', '80k', '100k']
FAMILIES_2CLK = {**FAMILIES, 'async_fifo': (8.0, 'Dual-clock FIFO banks with Gray pointers and two-stage synchronizers')}


def constraints(family):
    period = FAMILIES_2CLK[family][0]
    result = dict(clocks={'clk_a': period, 'clk_b': period * 1.5}, max_delays=[])
    if family == 'async_fifo':
        result['max_delays'] = [dict(source='clk_a', capture='clk_b', ns=6.0),
                                dict(source='clk_b', capture='clk_a', ns=7.0)]
    return result


def render(family, units, target):
    spec = constraints(family)
    header = (f'// {FAMILIES_2CLK[family][1]}.\n'
              f'// Target: {target} total mapped cells (+/-10%), across both domains.\n'
              f'// Clocks (ns): {spec["clocks"]}; constraints: {family}.json.\n'
              '// Generated by tests/placing/generate_2clk.py.\n')
    if family != 'async_fifo':
        a, b = units // 2, units - units // 2
        cores = render_single(family, a, target).replace('module top #', 'module core_a #')
        cores += render_single(family, b, target).replace('module top #', 'module core_b #')
        # Separate streams retain both domains without unsafe implicit crossings.
        wrapper = '''module top(input wire clk_a, clk_b,
  input wire [31:0] data_in, output wire [31:0] data_out);
  wire [15:0] a, b;
  core_a domain_a(.clk(clk_a), .data_in(data_in[15:0]), .data_out(a));
  core_b domain_b(.clk(clk_b), .data_in(data_in[31:16]), .data_out(b));
  assign data_out = {b,a};
endmodule
'''
        if family == 'map_reduce':
            # Register external samples before each multiplier map. This also
            # exercises a clocked launch at the distribution boundary.
            wrapper = wrapper.replace('  wire [15:0] a, b;', '''  wire [15:0] a, b;
  logic [15:0] input_a, input_b;
  always @(posedge clk_a) input_a <= data_in[15:0];
  always @(posedge clk_b) input_b <= data_in[31:16];''')
            wrapper = wrapper.replace('.data_in(data_in[15:0])', '.data_in(input_a)')
            wrapper = wrapper.replace('.data_in(data_in[31:16])', '.data_in(input_b)')
            if target == 1000:
                # Another map lane overshoots this tier; capture each output
                # in its own domain for finer mapped-size calibration.
                wrapper = wrapper.replace('  assign data_out = {b,a};', '''  logic [15:0] output_a1, output_a2, output_b1, output_b2;
  always @(posedge clk_a) begin
    output_a1 <= a;
    output_a2 <= output_a1;
  end
  always @(posedge clk_b) begin
    output_b1 <= b;
    output_b2 <= output_b1;
  end
  assign data_out = {output_b2,output_a2};''')
        return header + wrapper + cores
    return header + f'''module top #(parameter integer UNITS = {units})(
  input wire clk_a, clk_b, input wire [15:0] data_in,
  output wire [11:0] data_out);
  localparam integer LEAVES = 2**$clog2(UNITS);
  logic [11:0] tree [1:2*LEAVES-1];
  for (genvar i=0; i<UNITS; i=i+1) begin: bank
    logic [11:0] mem [0:7];
    logic [15:0] producer = i+1, consumer = i+3;
    logic [3:0] wbin = 0, wgray = 0, rbin = 0, rgray = 0;
    (* async_reg = "true" *) logic [3:0] rgray_meta = 0, rgray_sync = 0;
    (* async_reg = "true" *) logic [3:0] wgray_meta = 0, wgray_sync = 0;
    logic full = 0, empty = 1;
    wire push = (data_in[i%16] ^ producer[0]) && !full;
    wire pop = consumer[0] && !empty;
    wire [3:0] wnext = wbin + push, rnext = rbin + pop;
    wire [3:0] wg_next = (wnext >> 1) ^ wnext;
    wire [3:0] rg_next = (rnext >> 1) ^ rnext;
    always @(posedge clk_a) begin
      producer <= producer + (2*i+1);
      rgray_meta <= rgray; rgray_sync <= rgray_meta;
      wbin <= wnext; wgray <= wg_next;
      full <= wg_next == {{~rgray_sync[3:2],rgray_sync[1:0]}};
      if (push) mem[wbin[2:0]] <= data_in + producer;
    end
    always @(posedge clk_b) begin
      consumer <= consumer + (2*i+3);
      wgray_meta <= wgray; wgray_sync <= wgray_meta;
      rbin <= rnext; rgray <= rg_next;
      empty <= rg_next == wgray_sync;
      if (pop) tree[LEAVES+i] <= mem[rbin[2:0]];
    end
  end
  for (genvar i=UNITS; i<LEAVES; i=i+1) begin: pad
    assign tree[LEAVES+i] = 16'b0;
  end
  for (genvar i=1; i<LEAVES; i=i+1) begin: reduce
    always @(posedge clk_b) tree[i] <= tree[2*i] ^ tree[2*i+1];
  end
  assign data_out = tree[1];
endmodule
'''


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('size', choices=SIZES)
    p.add_argument('--yosys', required=True)
    p.add_argument('--family', choices=list(FAMILIES_2CLK))
    p.add_argument('--jobs', type=int, default=4, help='independent families to synthesize concurrently')
    args = p.parse_args()
    if args.jobs < 1:
        p.error('--jobs must be positive')
    target = int(args.size[:-1])*1000
    dest = ROOT / args.size / '2clk'
    dest.mkdir(exist_ok=True)
    manifest_file = dest / 'manifest.json'
    manifest = json.loads(manifest_file.read_text()) if manifest_file.exists() else {}
    previous = {}
    index = SIZES.index(args.size)
    if index:
        previous = json.loads((ROOT / SIZES[index-1] / '2clk' / 'manifest.json').read_text())
    def calibrate(family):
        minimum = 2
        units = max(minimum, round(target / (450 if family == 'async_fifo' else 150)))
        if family in previous:
            units = max(minimum, round(previous[family]['units']*target/previous[family]['cells']))
        elif family in FAMILIES:
            old = json.loads((ROOT / args.size / 'manifest.json').read_text())[family]
            units = max(minimum, old['units'])
        best, tried = None, set()
        with tempfile.TemporaryDirectory(prefix='scalepnr-2clk-') as tmp:
            work = Path(tmp)
            for attempt in range(14):
                source = work / (family+'.sv')
                source.write_text(render(family, units, target))
                metadata = synthesize(args.yosys, source, work)
                count = metadata['cells']
                print(args.size, family, units, count, flush=True)
                error = abs(count-target)/target
                if best is None or error < best[0]:
                    best = (error, units, source.read_text(), metadata)
                if error <= .035:
                    break
                tried.add(units)
                proposed = max(minimum, round(units*target/count))
                if proposed in tried:
                    # Nonlinear mapping can make proportional rounding stall.
                    proposed = units + (1 if count < target else -1)
                if proposed < minimum or proposed in tried:
                    break
                units = proposed
        error, units, source, metadata = best
        if error > .10:
            raise RuntimeError(f'{family}: closest count {metadata["cells"]}, outside tolerance')
        (dest/(family+'.sv')).write_text(source)
        spec = constraints(family)
        (dest/(family+'.json')).write_text(json.dumps(spec, indent=2)+'\n')
        (dest/(family+'.tcl')).write_text(constraint_tcl(spec))
        return family, dict(target=target, units=units, description=FAMILIES_2CLK[family][1],
                            constraints=spec, **metadata)
    with ThreadPoolExecutor(max_workers=args.jobs) as workers:
        futures = [workers.submit(calibrate, family)
                   for family in ([args.family] if args.family else FAMILIES_2CLK)]
        for future in as_completed(futures):
            family, result = future.result()
            manifest[family] = result
            manifest_file.write_text(json.dumps(manifest, indent=2, sort_keys=True)+'\n')


if __name__ == '__main__':
    main()
