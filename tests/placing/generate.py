#!/usr/bin/env python3
"""Generate ONE size tier; calibrate RTL parameters using the actual Yosys flow."""
import argparse
import json
import math
from pathlib import Path
import subprocess
import tempfile
from run import synthesize

ROOT = Path(__file__).resolve().parent
# Periods are fixed across sizes, in the documented abstract delay model.
FAMILIES = {
    'arithmetic_pipeline': (5.0, 'Feed-forward, three-stage add/rotate/XOR pipeline'),
    'systolic_fir': (6.0, 'Nearest-neighbor systolic constant-coefficient FIR sections'),
    'map_reduce': (8.0, 'Registered sample distribution, multiply map and balanced registered sum tree'),
    'ram_lookup': (10.0, 'Banked synchronous RAM read/modify/write stream'),
    'fifo_stream': (8.0, 'Cascaded circular FIFO queues with local read/write pointers and occupancy'),
    'crossbar_switch': (6.0, 'Registered four-way crossbar with local data-dependent selection'),
    'crc_feedback': (5.0, 'CRC-16 polynomial feedback with streamed inter-stage data'),
    'stencil_mesh': (6.0, 'Two-dimensional registered five-point stencil with neighbor exchange'),
    'priority_arbiter': (8.0, 'Distributed round-robin request masking and priority selection'),
    'compare_exchange': (6.0, 'Pipelined unsigned compare/exchange network'),
}

BODIES = {
'arithmetic_pipeline': '''
  logic [15:0] a, b, c;
  always @(posedge clk) begin
    a <= x + (16'h1357 + i);
    b <= {a[10:0],a[15:11]} ^ (a >> 3);
    c <= b + {b[7:0],b[15:8]};
  end
  assign y = c;
''',
'systolic_fir': '''
  logic [15:0] d0, d1, d2, p0, p1, p2, p2_delayed, sum;
  always @(posedge clk) begin
    d0 <= x; d1 <= d0; d2 <= d1;
    p0 <= d0 * 3; p1 <= d1 * 5; p2 <= d2 * 7;
    sum <= p0 + p1; p2_delayed <= p2; y <= sum + p2_delayed;
  end
''',
'ram_lookup': '''
  logic [15:0] mem [0:15];
  logic [3:0] address = i % 16;
  logic [15:0] read_data;
  always @(posedge clk) begin
    address <= address + 1'b1;
    mem[address] <= x ^ read_data;
    read_data <= mem[address + 4'd3];
    y <= read_data + x;
  end
''',
'fifo_stream': '''
  logic [15:0] mem [0:7];
  logic [2:0] wr = 0, rd = 0;
  logic [3:0] used = 0;
  wire push = x[0] && used != 8;
  wire pop = x[1] && used != 0;
  always @(posedge clk) begin
    if (push) begin mem[wr] <= x; wr <= wr + 1'b1; end
    if (pop) begin y <= mem[rd]; rd <= rd + 1'b1; end
    case ({push,pop})
      2'b10: used <= used + 1'b1;
      2'b01: used <= used - 1'b1;
      default: used <= used;
    endcase
  end
''',
'crossbar_switch': '''
  logic [15:0] a, b, c, d;
  logic [15:0] o0, o1, o2, o3;
  always @(posedge clk) begin
    a <= x; b <= a; c <= b; d <= c;
    case (x[1:0])
      0: begin o0<=a; o1<=b; o2<=c; o3<=d; end
      1: begin o0<=b; o1<=c; o2<=d; o3<=a; end
      2: begin o0<=c; o1<=d; o2<=a; o3<=b; end
      3: begin o0<=d; o1<=a; o2<=b; o3<=c; end
    endcase
    y <= o0 ^ {o1[10:0],o1[15:11]} ^ (o2 + o3);
  end
''',
'crc_feedback': '''
  logic [15:0] crc = 16'hffff;
  logic [15:0] next_crc;
  integer bit_index;
  always @* begin
    next_crc = crc;
    for (bit_index=0; bit_index<8; bit_index=bit_index+1)
      next_crc = {next_crc[14:0],1'b0} ^
        ((next_crc[15] ^ x[bit_index]) ? 16'h1021 : 16'h0000);
  end
  always @(posedge clk) begin crc <= next_crc; y <= crc ^ x; end
''',
'priority_arbiter': '''
  logic [15:0] mask = 16'hffff;
  wire [15:0] requests = x & mask;
  wire [15:0] eligible = (|requests) ? requests : x;
  wire [15:0] grant = eligible & (~eligible + 16'd1);
  always @(posedge clk) begin
    if (|grant) mask <= ~(grant | (grant - 16'd1));
    y <= grant ^ {x[14:0],x[15]};
  end
''',
'compare_exchange': '''
  logic [7:0] a, b, lo, hi;
  logic [15:0] delayed;
  always @(posedge clk) begin
    delayed <= x; a <= x[7:0]; b <= delayed[15:8];
    if (a < b) begin lo <= a; hi <= b; end
    else begin lo <= b; hi <= a; end
    y <= {hi,lo};
  end
''',
}

def render(family, units, target):
    period, desc = FAMILIES[family]
    header = f'''// Generated by tests/placing/generate.py; edit the generator to regenerate.
// {desc}.
// Target: {target} post-synthesis generic LUT/FF cells (+/-10%).
// Clock: {period:g} ns ({1000/period:g} MHz); see ../README.md for model/acceptance.
module top #(parameter integer UNITS = {units}) (
  input wire clk, input wire [15:0] data_in, output wire [15:0] data_out
);
'''
    if family == 'map_reduce':
        body = '''
  localparam integer LEAVES = 2**$clog2(UNITS);
  logic [15:0] samples [0:UNITS];
  logic [15:0] tree [1:2*LEAVES-1];
  assign samples[0] = data_in;
  for (genvar i=0; i<UNITS; i=i+1) begin: map
    always @(posedge clk) begin
      samples[i+1] <= samples[i];
      tree[LEAVES+i] <= samples[i][7:0] * samples[i][15:8];
    end
  end
  for (genvar i=UNITS; i<LEAVES; i=i+1) begin: pad
    assign tree[LEAVES+i] = 16'b0;
  end
  for (genvar i=1; i<LEAVES; i=i+1) begin: reduce
    always @(posedge clk) tree[i] <= tree[2*i] + tree[2*i+1];
  end
  assign data_out = tree[1];
'''
    elif family == 'stencil_mesh':
        columns = max(2, round(math.sqrt(units)))
        body = f'''
  localparam integer COLS = {columns};
  logic [15:0] q [0:UNITS-1];
  for (genvar i=0; i<UNITS; i=i+1) begin: mesh
    wire [15:0] west = i == 0 ? data_in : q[(i+UNITS-1)%UNITS];
    wire [15:0] east = q[(i+1)%UNITS];
    wire [15:0] north = q[(i+UNITS-COLS)%UNITS];
    wire [15:0] south = q[(i+COLS)%UNITS];
    always @(posedge clk) q[i] <= (q[i] >> 2) + (west >> 3)
      + (east >> 3) + (north >> 3) + (south >> 3);
  end
  assign data_out = q[UNITS-1];
'''
    else:
        body = '''
  wire [15:0] stream [0:UNITS];
  assign stream[0] = data_in;
  assign data_out = stream[UNITS];
  for (genvar i=0; i<UNITS; i=i+1) begin: stage
    wire [15:0] x = stream[i];
    logic [15:0] y;
    assign stream[i+1] = y;
''' + BODIES[family] + '  end\n'
    return header + body + 'endmodule\n'

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('size', choices=['1k','5k','10k','30k','50k','80k','100k'])
    p.add_argument('--yosys', required=True)
    p.add_argument('--family', choices=list(FAMILIES))
    args = p.parse_args()
    target = int(args.size[:-1])*1000
    dest = ROOT / args.size
    dest.mkdir(exist_ok=True)
    manifest_path = dest / 'manifest.json'
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}
    previous = {}
    sizes = ['1k','5k','10k','30k','50k','80k','100k']
    pos = sizes.index(args.size)
    if pos:
        previous = json.loads((ROOT / sizes[pos-1] / 'manifest.json').read_text())
    for family in ([args.family] if args.family else FAMILIES):
        units = max(2, round(target/150))
        if family in previous:
            units = max(2, round(previous[family]['units']*target/previous[family]['cells']))
        best = None
        tried = set()
        with tempfile.TemporaryDirectory(prefix='scalepnr-calibrate-') as tmp:
            work = Path(tmp)
            for attempt in range(12):
                source = work / (family + '.sv')
                source.write_text(render(family, units, target))
                metadata = synthesize(args.yosys, source, work)
                count = metadata['cells']
                print(args.size, family, units, count, flush=True)
                error = abs(count-target)/target
                if best is None or error < best[0]:
                    best = (error, units, source.read_text(), metadata)
                if error <= .035:
                    break
                tried.add(units)
                proposed = max(2, round(units*target/count))
                if proposed in tried:
                    break
                units = proposed
        error, units, source, metadata = best
        if error > .10:
            raise RuntimeError(f'{family}: cannot hit target, closest {metadata["cells"]}')
        (dest / (family + '.sv')).write_text(source)
        manifest[family] = dict(target=target, units=units, period_ns=FAMILIES[family][0],
                                description=FAMILIES[family][1], **metadata)
        manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True)+'\n')

if __name__ == '__main__':
    main()
